import * as fs from 'fs';
import * as path from 'path';

export interface AvailableChecks {
  test?: string;
  build?: string;
  lint?: string;
  typecheck?: string;
}

export interface ProjectInspection {
  isNodeProject: boolean;
  repoPath: string;
  packageJsonPath?: string;
  packageName?: string;
  version?: string;
  hasTsConfig: boolean;
  lockfile: 'npm' | 'yarn' | 'pnpm' | 'none';
  dependenciesInstalled: boolean;
  scripts: Record<string, string>;
  availableChecks: AvailableChecks;
  missingChecks: string[];
  recommendedCheck?: keyof AvailableChecks;
  notes: string[];
  error?: string;
}

const STANDARD_CHECKS: Array<keyof AvailableChecks> = ['test', 'build', 'lint', 'typecheck'];

/**
 * Checks whether an npm script is just the default placeholder generated by npm init.
 */
export function isPlaceholderTestScript(scriptContent?: string): boolean {
  if (!scriptContent) {
    return true;
  }
  const normalized = scriptContent.toLowerCase().replace(/['"]/g, '').replace(/\s+/g, ' ');
  return normalized.includes('no test specified') && normalized.includes('exit 1');
}

/**
 * Inspects a repository folder for Node.js / TypeScript configuration, scripts, and dependencies.
 */
export function inspectProject(repoPath: string): ProjectInspection {
  const notes: string[] = [];

  if (!repoPath || typeof repoPath !== 'string') {
    return {
      isNodeProject: false,
      repoPath: repoPath || '',
      hasTsConfig: false,
      lockfile: 'none',
      dependenciesInstalled: false,
      scripts: {},
      availableChecks: {},
      missingChecks: [...STANDARD_CHECKS],
      notes: ['Invalid repository directory path.'],
      error: 'Invalid repository directory path.',
    };
  }

  let stat: fs.Stats;
  try {
    if (!fs.existsSync(repoPath)) {
      return {
        isNodeProject: false,
        repoPath,
        hasTsConfig: false,
        lockfile: 'none',
        dependenciesInstalled: false,
        scripts: {},
        availableChecks: {},
        missingChecks: [...STANDARD_CHECKS],
        notes: ['Directory does not exist.'],
        error: `Repository directory does not exist: "${repoPath}"`,
      };
    }
    stat = fs.statSync(repoPath);
    if (!stat.isDirectory()) {
      return {
        isNodeProject: false,
        repoPath,
        hasTsConfig: false,
        lockfile: 'none',
        dependenciesInstalled: false,
        scripts: {},
        availableChecks: {},
        missingChecks: [...STANDARD_CHECKS],
        notes: ['Path is not a directory.'],
        error: `Specified path is not a directory: "${repoPath}"`,
      };
    }
  } catch (err: unknown) {
    const msg = err instanceof Error ? err.message : String(err);
    return {
      isNodeProject: false,
      repoPath,
      hasTsConfig: false,
      lockfile: 'none',
      dependenciesInstalled: false,
      scripts: {},
      availableChecks: {},
      missingChecks: [...STANDARD_CHECKS],
      notes: [`Filesystem access error: ${msg}`],
      error: `Filesystem error: ${msg}`,
    };
  }

  const pkgJsonPath = path.join(repoPath, 'package.json');
  if (!fs.existsSync(pkgJsonPath)) {
    return {
      isNodeProject: false,
      repoPath,
      hasTsConfig: fs.existsSync(path.join(repoPath, 'tsconfig.json')),
      lockfile: detectLockfile(repoPath),
      dependenciesInstalled: false,
      scripts: {},
      availableChecks: {},
      missingChecks: [...STANDARD_CHECKS],
      notes: ['No package.json found in repository root. Only Node.js/npm repositories are currently supported.'],
      error: 'No package.json found in repository root.',
    };
  }

  // Parse package.json
  let rawPkg: unknown;
  try {
    const content = fs.readFileSync(pkgJsonPath, 'utf8');
    rawPkg = JSON.parse(content);
  } catch (err: unknown) {
    const msg = err instanceof Error ? err.message : String(err);
    return {
      isNodeProject: true,
      repoPath,
      packageJsonPath: pkgJsonPath,
      hasTsConfig: fs.existsSync(path.join(repoPath, 'tsconfig.json')),
      lockfile: detectLockfile(repoPath),
      dependenciesInstalled: false,
      scripts: {},
      availableChecks: {},
      missingChecks: [...STANDARD_CHECKS],
      notes: [`Malformed package.json: ${msg}`],
      error: `Failed to parse package.json: ${msg}`,
    };
  }

  if (typeof rawPkg !== 'object' || rawPkg === null || Array.isArray(rawPkg)) {
    return {
      isNodeProject: true,
      repoPath,
      packageJsonPath: pkgJsonPath,
      hasTsConfig: fs.existsSync(path.join(repoPath, 'tsconfig.json')),
      lockfile: detectLockfile(repoPath),
      dependenciesInstalled: false,
      scripts: {},
      availableChecks: {},
      missingChecks: [...STANDARD_CHECKS],
      notes: ['package.json root is not an object.'],
      error: 'Invalid package.json structure: root must be an object.',
    };
  }

  const pkg = rawPkg as Record<string, unknown>;
  const packageName = typeof pkg.name === 'string' ? pkg.name : undefined;
  const version = typeof pkg.version === 'string' ? pkg.version : undefined;

  // Extract raw scripts
  const rawScripts = typeof pkg.scripts === 'object' && pkg.scripts !== null && !Array.isArray(pkg.scripts)
    ? (pkg.scripts as Record<string, unknown>)
    : {};

  const scripts: Record<string, string> = {};
  for (const [key, val] of Object.entries(rawScripts)) {
    if (typeof val === 'string') {
      scripts[key] = val;
    }
  }

  // Check tsconfig
  const hasTsConfig = fs.existsSync(path.join(repoPath, 'tsconfig.json'));
  if (hasTsConfig) {
    notes.push('TypeScript project configuration detected (tsconfig.json).');
  }

  // Detect lockfile
  const lockfile = detectLockfile(repoPath);
  if (lockfile !== 'none') {
    notes.push(`Detected package manager lockfile: ${lockfile}.`);
  }

  // Check dependencies installed
  const dependenciesInstalled = checkDependenciesInstalled(repoPath);
  if (!dependenciesInstalled) {
    notes.push('Dependencies do not appear to be installed (node_modules is missing or empty).');
  }

  // Detect checks
  const availableChecks: AvailableChecks = {};
  const missingChecks: string[] = [];

  // 1. test
  if (scripts['test']) {
    if (isPlaceholderTestScript(scripts['test'])) {
      notes.push('Default placeholder test script detected ("echo Error: no test specified"); treating test check as missing.');
      missingChecks.push('test');
    } else {
      availableChecks.test = scripts['test'];
    }
  } else {
    missingChecks.push('test');
  }

  // 2. build
  if (scripts['build']) {
    availableChecks.build = scripts['build'];
  } else {
    missingChecks.push('build');
  }

  // 3. lint
  if (scripts['lint']) {
    availableChecks.lint = scripts['lint'];
  } else {
    missingChecks.push('lint');
  }

  // 4. typecheck
  const typecheckKey = Object.keys(scripts).find((k) =>
    ['typecheck', 'type-check', 'tsc'].includes(k.toLowerCase())
  );
  if (typecheckKey) {
    availableChecks.typecheck = scripts[typecheckKey];
  } else {
    missingChecks.push('typecheck');
  }

  // Determine recommended check
  let recommendedCheck: keyof AvailableChecks | undefined;
  if (availableChecks.test) {
    recommendedCheck = 'test';
  } else if (availableChecks.build) {
    recommendedCheck = 'build';
  } else if (availableChecks.lint) {
    recommendedCheck = 'lint';
  } else if (availableChecks.typecheck) {
    recommendedCheck = 'typecheck';
  }

  return {
    isNodeProject: true,
    repoPath,
    packageJsonPath: pkgJsonPath,
    packageName,
    version,
    hasTsConfig,
    lockfile,
    dependenciesInstalled,
    scripts,
    availableChecks,
    missingChecks,
    recommendedCheck,
    notes,
  };
}

function detectLockfile(repoPath: string): 'npm' | 'yarn' | 'pnpm' | 'none' {
  if (fs.existsSync(path.join(repoPath, 'package-lock.json'))) {
    return 'npm';
  }
  if (fs.existsSync(path.join(repoPath, 'yarn.lock'))) {
    return 'yarn';
  }
  if (fs.existsSync(path.join(repoPath, 'pnpm-lock.yaml'))) {
    return 'pnpm';
  }
  return 'none';
}

function checkDependenciesInstalled(repoPath: string): boolean {
  const nodeModulesPath = path.join(repoPath, 'node_modules');
  try {
    if (!fs.existsSync(nodeModulesPath)) {
      return false;
    }
    const stat = fs.statSync(nodeModulesPath);
    if (!stat.isDirectory()) {
      return false;
    }
    const entries = fs.readdirSync(nodeModulesPath);
    // Ignore OS hidden files or isolated non-package entries
    const validEntries = entries.filter((e) => !e.startsWith('.') && e !== '.bin');
    return validEntries.length > 0;
  } catch {
    return false;
  }
}
